//! File business logic, with the live Files API rules and messages.

use std::sync::Arc;

use bytes::Bytes;
use shared::limits::required;
use shared::{ApiError, AuthContext, IdCursor, Timestamp};

use crate::store::{FilesStore, StoreError, StoredFile};
use crate::types::{FileId, FileMetadata, FileTag};
use crate::SessionFiles;

/// `expires_in_seconds` bounds (live files/10).
const EXPIRES_MIN: i64 = 3600;
const EXPIRES_MAX: i64 = 7_776_000;

/// The files list's filters.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct FileFilter {
    /// Only files in this scope (a session).
    pub scope_id: Option<String>,
    /// Only these files.
    pub ids: Vec<String>,
}

/// Files service.
pub struct FilesService {
    store: Arc<dyn FilesStore>,
    pub(crate) sessions: Arc<dyn SessionFiles>,
}

impl std::fmt::Debug for FilesService {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("FilesService").finish_non_exhaustive()
    }
}

impl FilesService {
    /// Build with a store, asking `sessions` which files a session reads.
    pub fn new(store: Arc<dyn FilesStore>, sessions: Arc<dyn SessionFiles>) -> Self {
        Self { store, sessions }
    }

    /// `POST /v1/files` (multipart). The filename keeps its last path
    /// component only (live files/04); an upload is not downloadable.
    pub async fn upload(
        &self,
        ctx: &AuthContext,
        filename: Option<String>,
        mime_type: Option<String>,
        bytes: Bytes,
        scope_id: Option<String>,
        expires_in_seconds: Option<String>,
    ) -> Result<FileMetadata, ApiError> {
        let filename = file_name(filename)?;
        let created_at = Timestamp::now();
        let expires_at = match expires_in_seconds {
            None => None,
            Some(raw) => {
                let secs = raw.trim().parse::<i64>().ok().filter(|s| (EXPIRES_MIN..=EXPIRES_MAX).contains(s));
                let secs = secs.ok_or_else(|| {
                    ApiError::invalid_request("expires_in_seconds: must be between 3600 and 7776000")
                })?;
                Some(Timestamp::from_datetime(created_at.as_datetime() + chrono::Duration::seconds(secs)))
            }
        };
        let mime_type = mime_type.unwrap_or_else(|| "application/octet-stream".into());
        let meta = FileMetadata {
            created_at,
            downloadable: false,
            expires_at,
            filename,
            id: FileId::generate(),
            mime_type,
            size_bytes: bytes.len() as u64,
            tag: FileTag::File,
            scope: None,
        };
        self.insert(ctx, meta, bytes, scope_id).await
    }

    pub(crate) async fn insert(
        &self,
        ctx: &AuthContext,
        meta: FileMetadata,
        bytes: Bytes,
        scope_id: Option<String>,
    ) -> Result<FileMetadata, ApiError> {
        self.store
            .insert(&ctx.workspace, StoredFile { meta: meta.clone(), bytes, scope_id })
            .await
            .map_err(|e| map_store(e, meta.id.as_str()))?;
        Ok(meta)
    }

    /// `GET /v1/files/{id}`; an expired file is not found.
    pub async fn metadata(&self, ctx: &AuthContext, raw_id: &str) -> Result<FileMetadata, ApiError> {
        Ok(self.live(ctx, raw_id).await?.meta)
    }

    /// `GET /v1/files/{id}/content`. Live (files/14): an uploaded file is not
    /// downloadable; only tool outputs are.
    pub async fn download(&self, ctx: &AuthContext, raw_id: &str) -> Result<(FileMetadata, Bytes), ApiError> {
        let file = self.live(ctx, raw_id).await?;
        if !file.meta.downloadable {
            let mut e = ApiError::invalid_request(format!(
                "File `{raw_id}` is not downloadable. Only files generated by a tool (for example, the code \
                 execution tool) can be downloaded."
            ));
            e.extra.insert("details".into(), serde_json::json!({"error_code": "file_not_downloadable"}));
            return Err(e);
        }
        Ok((file.meta, self.bytes(ctx, raw_id).await?))
    }

    pub(crate) async fn bytes(&self, ctx: &AuthContext, raw_id: &str) -> Result<Bytes, ApiError> {
        let id = parse_id(raw_id)?;
        self.store.content(&ctx.workspace, &id).await.map_err(|e| map_store(e, raw_id))
    }

    /// `GET /v1/files`: one id-cursor page and whether more remain, newest
    /// first; the store leaves expired files out.
    pub async fn list(
        &self,
        ctx: &AuthContext,
        filter: &FileFilter,
        cursor: &IdCursor,
    ) -> Result<(Vec<FileMetadata>, bool), ApiError> {
        let (files, has_more) =
            self.store.list(&ctx.workspace, filter, cursor).await.map_err(|e| map_store(e, ""))?;
        Ok((files.into_iter().map(|f| f.meta).collect(), has_more))
    }

    /// `DELETE /v1/files/{id}`.
    pub async fn delete(&self, ctx: &AuthContext, raw_id: &str) -> Result<FileMetadata, ApiError> {
        let id = parse_id(raw_id)?;
        self.store.delete(&ctx.workspace, &id).await.map(|f| f.meta).map_err(|e| map_store(e, raw_id))
    }

    pub(crate) async fn live(&self, ctx: &AuthContext, raw_id: &str) -> Result<StoredFile, ApiError> {
        let id = parse_id(raw_id)?;
        let file = self.store.get(&ctx.workspace, &id).await.map_err(|e| map_store(e, raw_id))?;
        if file.meta.expired(Timestamp::now()) {
            return Err(map_store(StoreError::NotFound, raw_id));
        }
        Ok(file)
    }
}

/// The upload's filename, its last path component only (live files/04).
pub(crate) fn file_name(filename: Option<String>) -> Result<String, ApiError> {
    let filename = required("file", filename)?;
    Ok(filename.rsplit(['/', '\\']).next().unwrap_or_default().to_owned())
}

/// Live (files/31): a malformed id is a 400 naming the prefix.
fn parse_id(raw: &str) -> Result<FileId, ApiError> {
    FileId::parse(raw).map_err(|_| ApiError::invalid_request("File id must have `file_` prefix."))
}

/// Live (files/30): ``File `file_…` not found.``
pub(crate) fn map_store(e: StoreError, raw_id: &str) -> ApiError {
    match e {
        StoreError::NotFound => ApiError::not_found(format!("File `{raw_id}` not found.")),
        StoreError::Backend(m) => ApiError::internal(m.to_string()),
    }
}
